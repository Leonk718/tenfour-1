/**
 * tenfour CLI — `tenfour init [--create-broker] [--workspace] [--same-human <peer>] [--yes]`
 * (CLI-MCP §1.1). Local install: create TENFOUR_HOME tree, copy bin entries, merge the
 * four hooks into ~/.claude/settings.json (backup + sentinel, abort on invalid JSON),
 * register the MCP server at user scope, initialize the journal, offer per-project gates.
 * All idempotent (re-running repairs).
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { tenfourPaths } from '../../../adapter/src/paths.ts';
import { claudeSettingsPath } from '../../../adapter/src/paths.ts';
import { Journal } from '../../../adapter/src/journal.ts';
import { loadConfig, saveConfig } from '../../../adapter/src/local-config.ts';
import { TenfourConfigSchema } from '../../../schema/src/config.ts';
import {
  parseSettings,
  mergeHooks,
  mergeGateRules,
  backupSettings,
  writeSettings,
  GATE_RULES_KEY,
} from '../settings.ts';
import { LocalError, type CliContext } from '../context.ts';
import { confirm } from '../prompt.ts';
import { out, err, type GlobalFlags } from '../output.ts';
import { EXIT } from '../exit-codes.ts';

const adapterSrcDir = (): string => fileURLToPath(new URL('../../../adapter/src', import.meta.url));

/** Write the two dependency-light bin entries pointing at the installed package source. */
function copyBinEntries(binDir: string): void {
  fs.mkdirSync(binDir, { recursive: true });
  const src = adapterSrcDir();
  const hookSrc = path.join(src, 'hooks', 'tenfour-hook.mjs');
  const mcpSrc = path.join(src, 'mcp', 'server.ts');
  const hookEntry = `#!/usr/bin/env node\n// tenfour hook entry (generated by tenfour init). Delegates to the installed adapter.\nimport { runHook } from ${JSON.stringify(hookSrc)};\nrunHook(process.argv[2]);\n`;
  const mcpEntry = `#!/usr/bin/env node\n// tenfour MCP entry (generated by tenfour init). Delegates to the installed adapter.\nimport { main } from ${JSON.stringify(mcpSrc)};\nmain().catch((e) => { process.stderr.write('tenfour-mcp: ' + (e?.message ?? e) + '\\n'); process.exit(1); });\n`;
  fs.writeFileSync(path.join(binDir, 'tenfour-hook.mjs'), hookEntry, { mode: 0o755 });
  fs.writeFileSync(path.join(binDir, 'tenfour-mcp.mjs'), mcpEntry, { mode: 0o755 });
}

function mergeGlobalHooks(hookEntryAbs: string, env: NodeJS.ProcessEnv): void {
  const file = claudeSettingsPath(env);
  const parsed = parseSettings(file);
  if (!parsed.ok) {
    // CLI §1.1 step 2: invalid existing JSON aborts with exit 2, file untouched.
    throw new LocalError(`~/.claude/settings.json is not valid JSON (${parsed.detail}); left untouched. Fix or remove it, then re-run tenfour init.`);
  }
  if (parsed.existed) backupSettings(file);
  writeSettings(file, mergeHooks(parsed.settings, hookEntryAbs));
}

function registerMcp(mcpEntryAbs: string): boolean {
  const res = spawnSync('claude', ['mcp', 'add', 'tenfour', '--scope', 'user', '--', 'node', mcpEntryAbs], { stdio: 'ignore' });
  return res.status === 0;
}

/** The base local install (steps 1–4): tree, bin entries, journal, hooks, MCP registration. */
export function baseInstall(flags: GlobalFlags, env: NodeJS.ProcessEnv = process.env): void {
  const paths = tenfourPaths(flags.home, env);
  fs.mkdirSync(paths.home, { recursive: true });
  copyBinEntries(paths.binDir);
  new Journal(paths.journalDir).ensure();
  mergeGlobalHooks(paths.hookEntry, env);
  out(`merged tenfour hooks into ${claudeSettingsPath(env)} (backup written; existing hooks untouched)`);
  const registered = registerMcp(paths.mcpEntry);
  out(registered ? 'registered MCP server tenfour at user scope' : 'could not run `claude mcp add` — register manually: claude mcp add tenfour --scope user -- node "' + paths.mcpEntry + '"');
}

export async function runInit(argv: string[], ctx: CliContext, flags: GlobalFlags): Promise<number> {
  const env = process.env;
  const wantWorkspace = argv.includes('--workspace');
  const wantCreateBroker = argv.includes('--create-broker');
  const sameHumanIdx = argv.indexOf('--same-human');
  const sameHuman = sameHumanIdx >= 0 ? argv[sameHumanIdx + 1] : undefined;
  const yes = argv.includes('--yes') || flags.json;
  const paths = tenfourPaths(flags.home, env);

  if (wantWorkspace) return runWorkspace(ctx, flags);

  baseInstall(flags, env);

  if (sameHuman) {
    out(`same-human mode: standing rules for peer ${sameHuman} will be pre-written at join.`);
  }

  if (wantCreateBroker) return runCreateBroker(paths.brokerSrcDir, flags);

  // Step 5 — per-project gate rules are opt-in, PER-PROJECT (run inside each repo).
  const offer = await confirm('Designate the current repo a tenfour workspace now (installs per-project gate rules)?', false, { yes });
  if (offer) return runWorkspace(ctx, flags);
  out('To designate a repo as a tenfour workspace later, run: tenfour init --workspace (inside that repo).');
  return EXIT.OK;
}

/** `--workspace`: must run inside a git repo; merge gate rules + append the repo path to workspaces[]. */
function runWorkspace(ctx: CliContext, flags: GlobalFlags): number {
  const cwd = process.cwd();
  const git = spawnSync('git', ['-C', cwd, 'rev-parse', '--show-toplevel'], { encoding: 'utf8' });
  if (git.status !== 0) {
    throw new LocalError('tenfour init --workspace must run inside a git repository.');
  }
  const repoRoot = git.stdout.trim();
  const settingsFile = path.join(repoRoot, '.claude', 'settings.json');
  const parsed = parseSettings(settingsFile);
  if (!parsed.ok) {
    throw new LocalError(`${settingsFile} is not valid JSON (${parsed.detail}); left untouched.`);
  }
  if (parsed.existed) backupSettings(settingsFile);
  writeSettings(settingsFile, mergeGateRules(parsed.settings));
  out(`installed per-project gate rules into ${settingsFile} (${GATE_RULES_KEY}=v1).`);

  // Append the repo path to workspaces[] (config.ts unchanged; repo_id derived on read).
  const cfgRes = loadConfig(flags.home);
  if (cfgRes.ok) {
    const ws = new Set(cfgRes.value.workspaces);
    ws.add(repoRoot);
    saveConfig(TenfourConfigSchema.parse({ ...cfgRes.value, workspaces: [...ws] }), flags.home);
    out(`tagged workspace ${repoRoot} in config.json.`);
  } else {
    err('note: config.json not found — workspace tagging recorded locally only; run tenfour join to create config.');
  }
  return EXIT.OK;
}

/** `--create-broker`: owner-side Convex provisioning. Requires broker-src + the Convex CLI. */
function runCreateBroker(brokerSrcDir: string, _flags: GlobalFlags): number {
  if (!fs.existsSync(brokerSrcDir)) {
    throw new LocalError(
      'tenfour init --create-broker needs the bundled broker-src staging dir, which is not present in this install. ' +
        'The broker is provisioned once by the owner via `npx convex deploy` in the broker package; point config.json broker_url at it, then run tenfour doctor.',
    );
  }
  const res = spawnSync('npx', ['convex', 'deploy'], { cwd: brokerSrcDir, stdio: 'inherit' });
  if (res.status !== 0) {
    throw new LocalError('Convex deploy failed; see the Convex output above. Fix the reported issue and re-run tenfour init --create-broker.');
  }
  out('broker deployed. Mint the owner agent with tenfour invite, then tenfour join on the owner machine.');
  return EXIT.OK;
}
